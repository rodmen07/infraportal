#!/usr/bin/env node
/**
 * sync-api-specs.mjs
 *
 * Reads the 11 committed OpenAPI YAML specs from the sibling microservices
 * checkout and emits deterministic JSON snapshots into src/api-specs/, plus a
 * small manifest.json the site uses for its service selector and derived
 * counts. Converting to JSON at sync time means no YAML parser ever ships in
 * the browser bundle; the snapshots are committed so the site builds offline.
 *
 * Usage:
 *   npm run sync-specs
 *   MICROSERVICES_DIR=../somewhere npm run sync-specs
 *   node ./scripts/sync-api-specs.mjs /path/to/microservices
 *
 * Tooling is pinned: the YAML parser is the exact-pinned `yaml` devDependency
 * in package.json. Output is deterministic (stable service order, 2-space
 * indent, trailing newline, no timestamps) so a re-run on an unchanged source
 * tree produces a byte-identical diff.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parseYaml } from 'yaml'

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']

/** Service ids in canonical (alphabetical) order. Directory = `${id}-service`. */
const SERVICE_IDS = [
  'accounts',
  'activities',
  'audit',
  'automation',
  'contacts',
  'integrations',
  'opportunities',
  'projects',
  'reporting',
  'search',
  'spend',
]

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..')
const outDir = join(repoRoot, 'src', 'api-specs')

const sourceRoot = resolve(
  process.argv[2] ?? process.env.MICROSERVICES_DIR ?? join(repoRoot, '..', 'microservices'),
)

if (!existsSync(sourceRoot)) {
  console.error(`error: microservices checkout not found at ${sourceRoot}`)
  console.error('Pass the path as an argument or set MICROSERVICES_DIR.')
  process.exit(1)
}

function displayName(id) {
  return id.charAt(0).toUpperCase() + id.slice(1)
}

function firstSentence(text) {
  if (!text) return ''
  const joined = text.replace(/\s+/g, ' ').trim()
  const period = joined.indexOf('. ')
  return period === -1 ? joined : joined.slice(0, period + 1)
}

function countOperations(spec) {
  let count = 0
  for (const pathItem of Object.values(spec.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      if (pathItem && typeof pathItem === 'object' && method in pathItem) count += 1
    }
  }
  return count
}

mkdirSync(outDir, { recursive: true })

const manifestServices = []

for (const id of SERVICE_IDS) {
  const yamlPath = join(sourceRoot, `${id}-service`, 'openapi.yaml')
  if (!existsSync(yamlPath)) {
    console.error(`error: missing spec ${yamlPath}`)
    process.exit(1)
  }

  const spec = parseYaml(readFileSync(yamlPath, 'utf8'))

  if (typeof spec?.openapi !== 'string' || !spec.openapi.startsWith('3.')) {
    console.error(`error: ${yamlPath} is not an OpenAPI 3.x document`)
    process.exit(1)
  }

  const outPath = join(outDir, `${id}-service.json`)
  writeFileSync(outPath, JSON.stringify(spec, null, 2) + '\n', 'utf8')

  const operationCount = countOperations(spec)
  manifestServices.push({
    id,
    name: displayName(id),
    title: spec.info?.title ?? `${id}-service`,
    version: spec.info?.version ?? 'unknown',
    summary: firstSentence(spec.info?.description),
    operationCount,
    tags: (spec.tags ?? []).map((tag) => tag.name),
  })

  console.log(`synced ${id}-service (${operationCount} operations) -> src/api-specs/${id}-service.json`)
}

const manifest = {
  note: 'Generated by scripts/sync-api-specs.mjs from the sibling microservices checkout. Do not edit by hand; run `npm run sync-specs` to refresh.',
  openapiVersion: '3.0.3',
  services: manifestServices,
}

writeFileSync(join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8')

const totalOps = manifestServices.reduce((sum, svc) => sum + svc.operationCount, 0)
console.log(`wrote manifest.json (${manifestServices.length} services, ${totalOps} operations)`)
